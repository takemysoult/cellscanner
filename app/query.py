def quote_1c(value: str) -> str:
    """Строка Python -> безопасный строковый литерал 1С.

    Литерал в 1С заключается в двойные кавычки, внутренняя кавычка удваивается.
    Это делает подстановку штрихкода в текст запроса защищённой от инъекции:
    сломать или расширить запрос содержимым штрихкода нельзя.
    """
    return '"' + (value or "").replace('"', '""') + '"'


def build_lookup_query(template: str, barcode: str) -> str:
    """Подставить штрихкод в шаблон запроса.

    Бросает ValueError, если в шаблоне нет плейсхолдера — иначе запрос молча
    вернул бы данные не по тому штрихкоду.
    """
    if PLACEHOLDER not in (template or ""):
        raise ValueError(
            f"В тексте запроса нет плейсхолдера {PLACEHOLDER} — "
            "подставить штрихкод некуда. Проверьте запрос в настройках.")
    return template.replace(PLACEHOLDER, quote_1c(barcode))


def normalize_barcode(raw: str) -> str:
    """Очистить то, что прислал сканер.

    Сканер-клавиатура может добавить перевод строки/табуляцию и пробелы по краям;
    внутренние пробелы для штрихкода не значимы и тоже убираются.
    """
    return "".join((raw or "").split())
